function apply(text) {
  for (const [a, r] of R) {
    let out = '', depth = 0;
    for (let i = 0; i < text.length;) {
      if (text[i] === '{') depth++;
      if (text[i] === '}') depth--;
      if (!depth && text.startsWith(a, i)) { out += `{${a}|${r}}`; i += a.length; continue; }
      out += text[i++];
    }
    text = out;
  }
  return text;
}
const F = path.join(__dirname, '../data/items.txt');
const out = fs.readFileSync(F, 'utf8').split(/\r?\n/).map(l => {
  if (l.startsWith('era|')) { const t = l.split('|'); return t.slice(0, 3).concat(apply(t.slice(3).join('|'))).join('|'); }
  if (l.startsWith('person|1|')) { const t = l.split('|'); return t.slice(0, 4).concat(apply(t.slice(4).join('|'))).join('|'); }
  return l;
});
fs.writeFileSync(F, out.join('\n'));
